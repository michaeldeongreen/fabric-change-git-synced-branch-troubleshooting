#requires -Version 5.1
[CmdletBinding()]
param(
    [ValidateSet('Identical', 'Divergent', 'Conflict')]
    [string]$Scenario = 'Identical'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$root = Split-Path $PSScriptRoot -Parent

function Invoke-LabGit {
    $result = & git -C $root -c credential.helper= -c 'credential.helper=!gh auth git-credential' @args
    if ($LASTEXITCODE -ne 0) { throw "git $($args -join ' ') failed." }
    return $result
}

$origin = Invoke-LabGit remote get-url origin
if ($origin -notmatch 'github\.com[:/]michaeldeongreen/fabric-change-git-synced-branch-troubleshooting(?:\.git)?$') {
    throw 'This helper is restricted to the private disposable lab repository.'
}
if (Invoke-LabGit status --porcelain) { throw 'Commit or preserve your local changes before running this helper.' }
Invoke-LabGit fetch origin | Out-Host
$originalBranch = Invoke-LabGit branch --show-current
if (-not $originalBranch) { throw 'Use a named local branch, not a detached HEAD.' }

try {
    Invoke-LabGit switch main | Out-Host
    Invoke-LabGit merge --ff-only origin/main | Out-Host
    $platforms = @(
        Get-ChildItem -LiteralPath (Join-Path $root 'fabric') -Filter '.platform' -File -Recurse -Force |
        Where-Object {
            $metadata = Get-Content -LiteralPath $_.FullName -Raw | ConvertFrom-Json
            $metadata.metadata.type -eq 'Lakehouse' -and $metadata.metadata.displayName -eq 'lh_git_consumer'
        }
    )
    if ($platforms.Count -ne 1) {
        throw 'First connect Fabric to main / fabric and commit the lab items in the Fabric UI. No shortcut schema or logical IDs will be invented.'
    }
    $platform = Get-Content -LiteralPath $platforms[0].FullName -Raw | ConvertFrom-Json
    if ([Guid]$platform.config.logicalId -eq [Guid]::Empty) {
        throw 'The consumer has an empty logical ID. Use the baseline generated by Fabric Git, not a raw pre-Git getDefinition export.'
    }
    foreach ($branch in @('dev', 'feature/shortcut-lab')) {
        $exists = & git -C $root show-ref --verify --quiet "refs/heads/$branch"
        if ($LASTEXITCODE -eq 1) {
            Invoke-LabGit switch --create $branch main | Out-Host
        }
        elseif ($LASTEXITCODE -eq 0) {
            Invoke-LabGit switch $branch | Out-Host
            Invoke-LabGit merge --ff-only "origin/$branch" | Out-Host
        }
        else { throw "Could not inspect branch $branch." }
        if ($Scenario -eq 'Identical') {
            Invoke-LabGit merge --ff-only main | Out-Host
            if ((Invoke-LabGit rev-parse HEAD) -ne (Invoke-LabGit rev-parse main)) {
                throw "$branch has already diverged. This helper will not reset or rewrite it."
            }
            Invoke-LabGit push --set-upstream origin $branch | Out-Host
        }
    }

    if ($Scenario -ne 'Identical') {
        Invoke-LabGit switch dev | Out-Host
        $platformPath = $platforms[0].FullName
        if ($Scenario -eq 'Divergent') {
            $path = Join-Path $platforms[0].DirectoryName 'shortcuts.metadata.json'
            $metadata = Get-Content -LiteralPath $path -Raw | ConvertFrom-Json
            $shortcuts = @($metadata | Where-Object { $_.name -eq 'branch_target' })
            if ($shortcuts.Count -ne 1) { throw 'Expected exactly one service-generated branch_target shortcut.' }
            $shortcuts[0].target.oneLake.path = 'Files/git-sync-lab/dev'
            $json = ConvertTo-Json -InputObject @($metadata) -Depth 30
            [IO.File]::WriteAllText($path, "$json`n", (New-Object Text.UTF8Encoding $false))
            Invoke-LabGit add -- $path | Out-Host
        }
        else {
            $platform = Get-Content -LiteralPath $platformPath -Raw | ConvertFrom-Json
            $platform.metadata.description = "Git-side same-item conflict control $([Guid]::NewGuid().ToString('N').Substring(0, 8)); synthetic lab only."
            $json = ConvertTo-Json -InputObject $platform -Depth 20
            [IO.File]::WriteAllText($platformPath, "$json`n", (New-Object Text.UTF8Encoding $false))
            Invoke-LabGit add -- $platformPath | Out-Host
        }
        $changed = Invoke-LabGit diff --cached --name-only
        if (-not $changed) { throw "$Scenario is already present. No new test change was committed." }
        Invoke-LabGit commit -m "Prepare $Scenario Fabric lab control" -m 'Co-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>' | Out-Host
        Invoke-LabGit push --set-upstream origin dev | Out-Host
    }
}
finally {
    if (Invoke-LabGit status --porcelain) {
        Write-Warning 'Left the current branch in place to preserve uncommitted changes after an error.'
    }
    else {
        Invoke-LabGit switch $originalBranch | Out-Host
    }
}

Write-Output "Prepared $Scenario repository scenario. This does not switch the Fabric workspace's branch."
